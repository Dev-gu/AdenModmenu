import re,sys
N=(sys.argv[1] if len(sys.argv)>1 else '../NHSE')+'/NHSE.Core/'
rec=[int(m,16) for m in re.findall(r'\{0x([0-9A-Fa-f]+),\s*\d+\}', open(N+'Structures/RecipeList.cs',encoding='utf-8-sig').read())]
rec=sorted(set(r for r in rec if r not in (0x1CA,0x1CD) and r<0x800))
bits=bytearray(0x100)
for r in rec: bits[r>>3]|=1<<(r&7)
react=[]
for name,val in re.findall(r'^\s*(\w+)\s*=\s*(\d+)', open(N+'Structures/Misc/Reaction.cs',encoding='utf-8-sig').read(), re.M):
    if name.startswith('UNUSED') or name=='None': continue
    react.append(int(val))
species=re.findall(r'^\s*(\w{3})\s*=\s*(\d+)', open(N+'Structures/Villager/VillagerUtil.cs',encoding='utf-8-sig').read(), re.M)
sp={n:int(v) for n,v in species}
names={}
for line in open(N+'Resources/text/en/text_villager_en.txt',encoding='utf-8-sig'):
    p=line.rstrip('\n').split('\t')
    if len(p)==2 and len(p[0])==5 and p[0][:3] in sp:
        nm=p[1].encode('ascii','replace').decode()
        names[(sp[p[0][:3]],int(p[0][3:]))]=nm
o=open('src/tables.c','w')
o.write('/* generated by tools/gen_tables.py from NHSE data */\n#include "nn.h"\n')
o.write('const u8 g_recipe_valid[0x100]={%s};\nconst int g_nrecipes=%d;\n'%(','.join(str(b) for b in bits),len(rec)))
o.write('const u8 g_reactions[]={%s};\nconst int g_nreactions=%d;\n'%(','.join(map(str,react)),len(react)))
o.write('typedef struct{u8 sp,var;const char* name;} VName;\nconst VName g_vnames[]={\n')
for (s,v),nm in sorted(names.items()): o.write('{%d,%d,"%s"},\n'%(s,v,nm.replace('"','')))
o.write('};\nconst int g_nvnames=%d;\n'%len(names))
print(len(rec),'recipes',len(react),'reactions',len(names),'villagers')
