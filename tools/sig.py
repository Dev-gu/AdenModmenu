#!/usr/bin/env python3
"""Build masked AArch64 code signatures from the 3.0.2 main binary.
Each signature = list of (value, mask) words. Masked out: anything that changes when
code or data moves (adrp pages, add/ldr low-12 offsets off an adrp register, bl/b
targets, literal loads). A signature is grown until it matches exactly once."""
import numpy as np, sys
TEXT_END = 0x3f06de0
d = open(sys.argv[1] if len(sys.argv) > 1 else 'main.bin', 'rb').read()
W = np.frombuffer(d[:TEXT_END], dtype='<u4')

def mask_window(words):
    vals, masks = [], []
    adrp_regs = set()
    for x in words:
        x = int(x); m = 0xFFFFFFFF
        if (x & 0x9F000000) == 0x90000000:            # adrp
            m = 0x9F00001F; adrp_regs.add(x & 31)
        elif (x & 0x7F800000) == 0x11000000 and ((x >> 5) & 31) in adrp_regs:   # add imm off adrp reg
            m = 0xFFC003FF
        elif (x & 0x3B000000) == 0x39000000 and ((x >> 5) & 31) in adrp_regs:   # ldr/str uimm off adrp reg
            m = 0xFFC003FF
        elif (x & 0x7C000000) == 0x14000000:          # b / bl
            m = 0xFC000000
        elif (x & 0x3B000000) == 0x18000000:          # ldr literal
            m = 0xFF00001F
        vals.append(x & m); masks.append(m)
    return vals, masks

def count(vals, masks, limit=3):
    v = np.array(vals, dtype=np.uint32); m = np.array(masks, dtype=np.uint32)
    cand = np.nonzero((W[:len(W) - len(v)] & m[0]) == v[0])[0]
    for j in range(1, len(v)):
        cand = cand[(W[cand + j] & m[j]) == v[j]]
        if len(cand) == 0: break
    return cand

def make(addr, before=0, minlen=6, extra=4, maxlen=40):
    """signature covering [addr-before*4, ...); returns (start_off, vals, masks)"""
    start = addr // 4 - before
    for n in range(minlen, maxlen + 1):
        vals, masks = mask_window(W[start:start + n])
        c = count(vals, masks)
        if len(c) == 1 and c[0] == start:
            n2 = min(n + extra, maxlen)
            vals, masks = mask_window(W[start:start + n2])
            assert list(count(vals, masks)) == [start]
            return start * 4, vals, masks
    raise SystemExit('no unique signature for %x' % addr)

def resolve_adrp(pos):
    """decode adrp at word index pos and its paired add/ldr -> target address"""
    x = int(W[pos]); rd = x & 31
    imm = (((x >> 5) & 0x7FFFF) << 2) | ((x >> 29) & 3)
    if imm & (1 << 20): imm -= 1 << 21
    page = ((pos * 4) & ~0xFFF) + (imm << 12)
    for j in range(pos + 1, pos + 12):
        y = int(W[j])
        if ((y >> 5) & 31) != rd: continue
        if (y & 0x7F800000) == 0x11000000:
            o = (y >> 10) & 0xFFF
            if (y >> 22) & 1: o <<= 12
            return page + o, j - pos
        if (y & 0x3B000000) == 0x39000000:
            size = (y >> 30) & 3; v = (y >> 26) & 1; opc = (y >> 22) & 3
            sc = 4 if (v and opc >= 2) else size
            return page + (((y >> 10) & 0xFFF) << sc), j - pos
    return None, None

if __name__ == '__main__':
    # code targets: hook / call at function start
    CODE = [('APPAVAIL', 0x2e5a0d0), ('EVCHECK', 0x264bce0), ('LAUNCH16', 0x2e03250),
            ('DBGDRAW', 0x3b1bcd0), ('TW_SETUP', 0x37e4d80), ('U8TO16', 0x37d4ca0), ('TW_PRINT', 0x37e7454)]
    # data targets: (name, expected address, adrp site)
    DATA = [('FONT_A', 0x4ad0ef8, 0x3b1bd14), ('FONT_B', 0x4ad0c58, 0x3b1bd20), ('TW_VT', 0x4ad0f00, 0x3b1bd10),
            ('TW_SETUP_ARG', 0x59e7800, 0x3b1bdfc), ('PRIM_MGR', 0x59e74c0, 0x37b0f48)]
    out = []
    for name, a in CODE:
        s, v, m = make(a)
        out.append((name, 'code', s, 0, v, m)); print(name, hex(a), len(v), 'words', file=sys.stderr)
    for name, target, site in DATA:
        got, _ = resolve_adrp(site // 4); assert got == target, (name, hex(got or 0))
        s, v, m = make(site, before=4)
        out.append((name, 'data', s, (site - s) // 4, v, m)); print(name, hex(target), len(v), 'words, adrp at word', (site - s) // 4, file=sys.stderr)
    # emit C
    print('/* generated by tools/sig.py from ACNH 3.0.2 main - do not edit */')
    print('#include "nn.h"')
    print('#include "sigs.h"')
    for name, kind, s, k, v, m in out:
        print('static const u32 %s_v[]={%s};' % (name, ','.join('0x%08x' % x for x in v)))
        print('static const u32 %s_m[]={%s};' % (name, ','.join('0x%08x' % x for x in m)))
    print('const Sig g_sigs[SIG_COUNT]={')
    for name, kind, s, k, v, m in out:
        print('  {"%s",%d,%s_v,%s_m,%d,%d,0x%x},' % (name, 1 if kind == 'data' else 0, name, name, len(v), k, s))
    print('};')
    print('/* enum order */', file=sys.stderr)
    print(' '.join('SIG_' + o[0] for o in out), file=sys.stderr)
